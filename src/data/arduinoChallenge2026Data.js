/**
 * Helper function to format component constraints table
 */
export function formatComponentTable() {
  return arduinoChallenge2026.projectGuidelines.allowedComponents.components;
}

/**
 * Helper function to get timeline events
 */
export function getTimelineEvents() {
  const events = [];
  arduinoChallenge2026.structure.phases.forEach((phase) => {
    phase.events.forEach((event) => {
      events.push({
        phase: phase.name,
        ...event,
      });
    });
  });
  return events;
}
